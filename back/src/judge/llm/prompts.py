# ユーザーに見せるコメントに出てはいけない、開発者目線の言葉
FORBIDDEN_WORDS = (
    "選ば", "選び", "選択", "関連", "紐づ", "紐付", "対応", "割り当", "分類", "判定", "評価", "診断", "分析",
    "データ", "計測", "数値", "スコア", "点数", "ランク", "レベル", "候補", "カテゴリ", "パターン",
    "デザイナー", "デザイン担当", "カタログ", "レアリティ", "システム", "AI", "ＡＩ", "アルゴリズム", "画像",
)


def forbidden_words_in(text: str) -> list[str]:
    return [w for w in FORBIDDEN_WORDS if w in text]


def comment_user_text(*, sock_label: str, impression_label: str, quality_rank: int, special_note: str | None,
                      judge_reason: str | None, feature_text: list[str], description: dict | None,
                      has_image: bool = False) -> str:
    quality_words = {
        1: "まだ粗さが目立つ（靴下はくたびれた仕立て）",
        2: "やや粗さがある（素朴な仕立て）",
        3: "標準的に整っている（ふつうの仕立て）",
        4: "よく整っている（上質な仕立て）",
        5: "とても整っている（最上の仕立て）",
    }[quality_rank]
    sock = description or {}
    material = {
        "靴下の名前": sock.get("名前") or sock_label,
        "靴下の見た目": sock.get("見た目"),
        "この靴下に込められたもの": sock.get("この靴下が合う理由"),
        "この「と」の性格": impression_label,
        "この「と」の書きぶり": [judge_reason] + feature_text if judge_reason else feature_text,
        "字の整い具合": quality_words,
        "特別な書きぶり": special_note,
    }
    if has_image:
        head = "1枚目はあなたが語りかける相手が書いた「と」、2枚目はその「と」から編み上がった靴下です。\n"
    elif description:
        head = "1枚目はあなたが語りかける相手が書いた「と」です。編み上がった靴下の見た目は下の「靴下の見た目」を使ってください。\n"
    else:
        head = (
            "1枚目はあなたが語りかける相手が書いた「と」です。靴下の見た目はまだ分からないので、"
            "色・柄・飾りなど具体的な見た目には触れず、書きぶりから想像される靴下の雰囲気（素材感や履き心地のたとえ）だけで語ってください。\n"
        )
    return (
        head
        + "語るための材料（このままユーザーに見せない）:\n"
        + json.dumps({k: v for k, v in material.items() if v}, ensure_ascii=False)
        + "\n編み上がった靴下を手渡す言葉を書いてください。"
    )
